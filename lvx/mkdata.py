#!/usr/bin/env python3
"""Bake a reference and a set of reads from demo/*.fa into lvx/data.h.

The ISS runs bare metal -- crt.S provides write(2) and exit(2) and nothing
else -- so there is no filesystem to read a FASTA from at run time.  Baking
keeps the benchmark deterministic and self-contained, and keeps the data's
provenance explicit: this script names the upstream files it came from, so a
regenerated header is reproducible rather than a blob nobody can re-derive.

    ./lvx/mkdata.py demo/1k.fa demo/54mer_hap1_1.100.fa 8 > lvx/data.h
"""
import sys

def fasta(path):
    seqs, name, cur = [], None, []
    for line in open(path):
        line = line.strip()
        if line.startswith('>'):
            if name is not None:
                seqs.append((name, ''.join(cur)))
            name, cur = line[1:], []
        elif line:
            cur.append(line)
    if name is not None:
        seqs.append((name, ''.join(cur)))
    return seqs

ref_path, qry_path, nq = sys.argv[1], sys.argv[2], int(sys.argv[3])
ref = fasta(ref_path)[0]
qrys = fasta(qry_path)[:nq]

def emit(name, seq):
    print(f'static const char {name}[] =')
    for i in range(0, len(seq), 68):
        print(f'  "{seq[i:i+68]}"')
    print('  ;')

print('/* GENERATED by lvx/mkdata.py -- do not edit. */')
print(f'/* reference: {ref_path}, "{ref[0]}", {len(ref[1])} bp */')
print(f'/* queries:   {qry_path}, first {len(qrys)} reads */')
print('#if !defined(LVX_SSW_DATA_H)')
print('#define LVX_SSW_DATA_H')
print()
emit('ssw_ref', ref[1])
print(f'#define SSW_REF_LEN {len(ref[1])}')
print()
print(f'#define SSW_NQUERY {len(qrys)}')
print('static const char *const ssw_query[SSW_NQUERY] = {')
for n, s in qrys:
    print(f'  /* {n} */')
    print(f'  "{s}",')
print('};')
print('static const int ssw_query_len[SSW_NQUERY] = {')
print('  ' + ', '.join(str(len(s)) for _, s in qrys))
print('};')
print()
print('#endif /* LVX_SSW_DATA_H */')
