#!/usr/bin/env bash
# Regenerate harness/reference-checksums.tsv from the NATIVE x86 builds.
#
#   ./harness/make-reference.sh
#
# The committed checksums are the correctness oracle the LVX runs are gated
# against, and they are generated here rather than recorded from an LVX run on
# purpose: a reference taken from the target cannot detect a target miscompile,
# it can only perpetuate one.  lvx-polybench's reference-output/ is built the
# same way and for the same reason.
#
# Both drivers compute exact integer scores from baked data with no floating
# point anywhere, so the checksum is a bit-exact invariant of the algorithm and
# the input -- not of the host.  A difference between this file and an LVX run
# is a real defect, never tolerance.
#
# Regenerate when lvx/data.h changes, or when a driver deliberately changes
# what it computes -- and say which in the commit message, because this file
# moving is otherwise indistinguishable from a bug being normalised away.
set -u
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(dirname "$here")"
out="$here/reference-checksums.tsv"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' 0 1 2 3 15

{
    printf '# GENERATED by harness/make-reference.sh from the native x86 builds.\n'
    printf '# bench\tchecksum\n'
} > "$tmp/out"

rc=0
for bench in striped inter; do
    case $bench in
        striped) src="$repo/lvx/lvx-bench.c $repo/src/ssw.c" ;;
        inter)   src="$repo/lvx/lvx-inter.c" ;;
    esac
    # shellcheck disable=SC2086
    cc -O2 -I"$repo/src" -o "$tmp/$bench" $src -lm || { echo "native build failed: $bench" >&2; rc=1; continue; }
    cks=$("$tmp/$bench" t 2>/dev/null | sed -n 's/^checksum \(.*\)$/\1/p' | tail -1)
    if [ -z "$cks" ]; then
        echo "no checksum from the native $bench run -- did its self-check fail?" >&2
        rc=1; continue
    fi
    printf '%s\t%s\n' "$bench" "$cks" >> "$tmp/out"
    printf '%-10s %s\n' "$bench" "$cks"
done

[ "$rc" = 0 ] || { echo "not writing $out" >&2; exit 1; }
mv "$tmp/out" "$out"
echo
echo "wrote $out"
